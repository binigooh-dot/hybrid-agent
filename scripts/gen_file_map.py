"""[SCRIPTS / docs] Regenerate docs/FILE_MAP.md: every file with its [LAYER / name] label.

    python scripts/gen_file_map.py

Labels come from the first line of each Python module's docstring (or the
first line of a Markdown/JSON file), so the map can't drift from the code.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {".git", "__pycache__", "workspace", "logs", ".venv"}
STATIC = {".gitignore": "[REPO] Files git should ignore (secrets, workspace, logs)",
          "hybrid_agent/gui/static/favicon.svg": "[GUI / icon] App icon",
          ".env.example": "[CONFIG] Every setting with its default; copy to .env",
          "pyproject.toml": "[PACKAGING] Package metadata; `pip install -e .[claude]`",
          "requirements-claude.txt": "[PACKAGING] Only needed for Claude; local mode needs nothing",
          "tests/__init__.py": "[TESTS] Package marker"}


def label(p: Path) -> str:
    rel = p.relative_to(ROOT).as_posix()
    if rel in STATIC:
        return STATIC[rel]
    try:
        if p.suffix == ".py":
            doc = ast.get_docstring(ast.parse(p.read_text(encoding="utf-8")))
            return (doc or "").strip().splitlines()[0] if doc else ""
        if p.suffix == ".md":
            first = p.read_text(encoding="utf-8").lstrip().splitlines()[0]
            return "[DOCS] " + first.lstrip("# ").strip()
        if p.suffix in {".html", ".css", ".js"}:
            head = p.read_text(encoding="utf-8")[:400]
            for marker in ("<!-- [", "/* [", "// ["):
                if marker in head:
                    return "[" + head.split(marker, 1)[1].split("]", 1)[0] + "]" + \
                        head.split(marker, 1)[1].split("]", 1)[1].split("\n")[0].rstrip(" */->")
        if p.suffix == ".json":
            return json.loads(p.read_text(encoding="utf-8")).get("_comment", "").split(".")[0]
    except (SyntaxError, IndexError, ValueError):
        pass
    return ""


def project_files() -> list[Path]:
    """Files git tracks plus new files that aren't git-ignored. Build artefacts
    (.coverage, caches, logs) therefore never appear. Falls back to a filtered
    walk when git isn't available."""
    import subprocess
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout
        files = [ROOT / line for line in out.splitlines() if line]
    except (OSError, subprocess.CalledProcessError):
        files = [f for f in ROOT.rglob("*") if f.is_file()]
    keep = {f for f in files if f.is_file() and not SKIP & set(f.relative_to(ROOT).parts)
            and f.name not in {"FILE_MAP.md", ".coverage"} and f.suffix != ".pyc"}
    # sort by the "/" path text, case-sensitively: Windows compares Path objects case-insensitively
    return sorted(keep, key=lambda f: f.relative_to(ROOT).as_posix())


def build() -> str:
    files = project_files()
    out = ["# File map\n\n> Generated by `scripts/gen_file_map.py`. Every Python module's docstring starts with "
           "its `[LAYER / name]` label, so this list stays in sync with the code.\n\n"
           "| File | Label / purpose |\n|---|---|\n"]
    for f in files:
        out.append(f"| `{f.relative_to(ROOT).as_posix()}` | {label(f).replace('|', '/')} |\n")
    return "".join(out)


if __name__ == "__main__":
    (ROOT / "docs" / "FILE_MAP.md").write_text(build(), encoding="utf-8")
    print("wrote docs/FILE_MAP.md")
