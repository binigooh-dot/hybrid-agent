"""[SCRIPTS / docs] Regenerate docs/FILE_MAP.md: every file with its [LAYER / name] label.

    python scripts/gen_file_map.py

Labels come from the first line of each Python module's docstring (or the
first line of a Markdown/JSON file), so the map can't drift from the code.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = {".git", "__pycache__", "workspace", "logs", ".venv"}
STATIC = {".gitignore": "[REPO] Files git should ignore (secrets, workspace, logs)",
          ".env.example": "[CONFIG] Every setting with its default; copy to .env",
          "pyproject.toml": "[PACKAGING] Package metadata; `pip install -e .[claude]`",
          "requirements-claude.txt": "[PACKAGING] Only needed for Claude; local mode needs nothing",
          "tests/__init__.py": "[TESTS] Package marker"}


def label(p: Path) -> str:
    rel = p.relative_to(ROOT).as_posix()
    if rel in STATIC:
        return STATIC[rel]
    try:
        if p.suffix == ".py":
            doc = ast.get_docstring(ast.parse(p.read_text()))
            return (doc or "").strip().splitlines()[0] if doc else ""
        if p.suffix == ".md":
            first = p.read_text().lstrip().splitlines()[0]
            return "[DOCS] " + first.lstrip("# ").strip()
        if p.suffix == ".json":
            return json.loads(p.read_text()).get("_comment", "").split(".")[0]
    except (SyntaxError, IndexError, ValueError):
        pass
    return ""


def build() -> str:
    files = sorted(f for f in ROOT.rglob("*") if f.is_file() and not SKIP & set(f.relative_to(ROOT).parts)
                   and f.name != "FILE_MAP.md")
    out = ["# File map\n\n> Generated by `scripts/gen_file_map.py`. Every Python module's docstring starts with "
           "its `[LAYER / name]` label, so this list stays in sync with the code.\n\n"
           "| File | Label / purpose |\n|---|---|\n"]
    for f in files:
        out.append(f"| `{f.relative_to(ROOT).as_posix()}` | {label(f).replace('|', '/')} |\n")
    return "".join(out)


if __name__ == "__main__":
    (ROOT / "docs" / "FILE_MAP.md").write_text(build())
    print("wrote docs/FILE_MAP.md")
