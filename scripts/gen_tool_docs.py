"""[SCRIPTS / docs] Regenerate docs/04_TOOLS.md from the live tool registry.

    python scripts/gen_tool_docs.py

Run this after adding or changing a tool; tests/test_tools_registry.py fails
if the doc is out of date.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from hybrid_agent.tools import PROFILES, ToolContext, build_full_registry, build_registry  # noqa: E402

HEADER = """\
# 04 · Tool reference

> Generated by `scripts/gen_tool_docs.py` from the code. Don't edit the tables by hand.

**{n} tools in {c} categories. None needs an API key.** Tools marked 🌐 contact the
internet (no key, but they need a connection).

Every tool has two labels:

| Label | Values | Used for |
|---|---|---|
| **category** | files, shell, code, data, text, math, time, web, network, knowledge, system, archives, memory, documents, agent, council | Grouping, profiles, `@category` in profile strings |
| **risk** | `read` < `network` < `write` < `execute` | Profiles (e.g. `readonly` has nothing above `network`), and deciding what needs approval |

✋ = asks y/N approval before running (skip the prompt with `-y`).
"""

PROFILE_INTRO = """
## Profiles: which tools each agent gets

The model receives every tool's description on every request. The full list is about
**{full_tok:,} tokens**, which would fill most of a small local model's 8k context, so agents get a
**profile** instead. Analogy: a plumber is sent with a plumber's toolbox, not the whole hardware store.

| Profile | Tools | ≈ tokens | Intended for |
|---|---|---|---|
"""
PURPOSE = {
    "minimal": "3B-class models; basic file work",
    "core": "**default for local models**; general purpose",
    "research": "researcher role; web + knowledge + document search",
    "coding": "engineer role; code, tests, git, shell",
    "data": "analyst role; CSV/JSON/SQLite + maths",
    "readonly": "chair/skeptic roles; look, don't touch",
    "readonly_all": "every non-writing tool (best with Claude)",
    "full": "**default with Claude**; everything",
}

FOOTER = """
Profile strings can be modified: `core,+weather,+git_status` adds tools, `core,@knowledge` adds a
category, and `full,-run_shell` removes a tool. Set one with `--tools`, `AGENT_TOOL_PROFILE`, or a
council member's `"tools"` field.

## Safety model

```
model asks for tool ─► schema check ─► approval (✋ tools) ─► safety checks ─► run ─► truncate output
                         │ bad args → error    │ "no" → error      │ path outside workspace → error
                         ▼                     ▼                   │ blocked shell command → error
                      model retries        model told "declined"   │ zip-slip in archives → error
```

- **Files:** every path goes through `resolve_in_workspace`, which blocks `..` and symlink escapes.
- **Secrets:** `env_vars` hides the values of variables whose names look like keys or tokens.
- **Writes:** `sqlite_query` and `http_request` ask for approval only for the writing forms (an UPDATE, a POST).
- The workspace fence protects files, but **`run_shell`, `run_python` and `run_tests` can reach anything
  your user account can.** For real isolation, run the agent in a container or VM.

## Adding a tool

```python
from hybrid_agent.tools import S, ToolError
from hybrid_agent.core.safety import resolve_in_workspace

@registry.tool(
    "word_count",                                        # the name the model calls
    "Count the words in a workspace text file.",         # the model reads this, so be specific
    S(path="string|Path in the workspace",               # "type|description"
      unique="boolean?|Count distinct words only"),      # "?" marks it optional
    category="text", risk="read",                        # labels (see above)
    requires_approval=False,
)
def word_count(ctx, path, unique=False):                 # parameters must match the schema exactly
    p = resolve_in_workspace(ctx.workspace, path)        # always use this for paths
    if not p.is_file():
        raise ToolError(f"No such file: {path}")         # ToolError → a message the model can act on
    words = p.read_text().split()
    return str(len(set(words)) if unique else len(words))
```

To ship a tool with the package, put it in a module under `hybrid_agent/tools/builtin/`, add the
module to `ALL_MODULES` in `builtin/__init__.py`, then run `python scripts/gen_tool_docs.py`.
`tests/test_tools_registry.py` checks that the schema matches the function signature and that every
tool is labelled and documented.

Tips for tools that small local models can use reliably: use few, obvious argument names; write
errors that say how to fix the call; keep output short.
"""


def build() -> str:
    import json
    ctx = ToolContext(workspace=Path("."))
    reg = build_full_registry(ctx)
    out = [HEADER.format(n=len(reg), c=len(reg.categories()))]
    tok = lambda r: round(len(json.dumps(r.specs())) / 4)  # noqa: E731
    out.append(PROFILE_INTRO.format(full_tok=tok(reg)))
    for name in PROFILES:
        r = build_registry(ctx, name)
        out.append(f"| `{name}` | {len(r)} | {tok(r):,} | {PURPOSE.get(name, '')} |\n")
    out.append("\n## Catalogue\n")
    for cat, names in reg.categories().items():
        out.append(f"\n### {cat}\n\n| Tool | Risk | What it does | Arguments |\n|---|---|---|---|\n")
        for n in names:
            t = reg.get(n)
            props = t.parameters.get("properties", {})
            req = set(t.parameters.get("required", []))
            args = ", ".join(f"`{p}`" if p in req else f"`{p}`?" for p in props) or "—"
            flags = ("🌐 " if t.risk == "network" else "") + ("✋ " if t.requires_approval else "")
            desc = t.description.replace("|", "\\|")
            out.append(f"| `{n}` | {flags}{t.risk} | {desc} | {args} |\n")
    out.append(FOOTER)
    return "".join(out)


if __name__ == "__main__":
    (ROOT / "docs" / "04_TOOLS.md").write_text(build())
    print("wrote docs/04_TOOLS.md")
